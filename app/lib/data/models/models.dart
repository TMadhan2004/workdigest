/// What my confirmed rules exclude, merged; the same logic the Mac applies to the digest
/// (`RuleFilters.excludes_pr`), so the app and the digest never disagree.
@immutable
class PrExclusions {
  const PrExclusions({this.prs = const {}, this.olderThanDays, this.tickets = const {}, this.repos = const {}});

  factory PrExclusions.fromRules(Iterable<StandingRule> rules) {
    final prs = <String?, Set<int>>{};
    int? days;
    final tickets = <String>{};
    final repos = <String>{};
    for (final rule in rules.where((r) => r.mine && r.status == 'active')) {
      for (final ref in objects(rule.params, 'exclude_prs')) {
        final repo = strOrNull(ref, 'repo')?.toLowerCase();
        prs.putIfAbsent(repo, () => <int>{}).addAll((ref['numbers'] as List<dynamic>? ?? const []).whereType<num>().map((n) => n.toInt()));
      }
      final limit = intOrNull(rule.params, 'exclude_prs_older_than_days');
      if (limit != null && (days == null || limit < days)) days = limit;
      tickets.addAll(strings(rule.params, 'exclude_tickets').map((t) => t.toUpperCase()));
      repos.addAll(strings(rule.params, 'exclude_repos').map((r) => r.toLowerCase()));
    }
    return PrExclusions(prs: prs, olderThanDays: days, tickets: tickets, repos: repos);
  }

  /// PR numbers per repo (null repo = any repo).
  final Map<String?, Set<int>> prs;
  final int? olderThanDays;
  final Set<String> tickets;
  final Set<String> repos;

  bool excludes(PullRequest pr, DateTime now) {
    final repo = pr.repo.toLowerCase();
    if (repos.contains(repo) || pr.ticketKeys.any((t) => tickets.contains(t.toUpperCase()))) return true;
    if ((prs[repo]?.contains(pr.prId) ?? false) || (prs[null]?.contains(pr.prId) ?? false)) return true;
    final limit = olderThanDays;
    return limit != null && now.difference(pr.openedAt).inDays > limit;
  }
}

/// Whether an AI provider works on the user's Mac, as last checked there.
@immutable
class AiCapability {
  const AiCapability({required this.state, this.detail = '', this.checkedAt});

  factory AiCapability.fromJson(Json json) => AiCapability(
    state: str(json, 'state', 'unknown'),
    detail: str(json, 'detail'),
    checkedAt: dateTimeOrNull(json, 'checked_at'),
  );

  /// ok, missing (not installed), logged_out, failing (e.g. subscription ended), unknown.
  final String state;
  final String detail;
  final DateTime? checkedAt;

  bool get usable => state == 'ok' || state == 'unknown';

  /// Why it cannot be chosen, in plain words.
  String get reason => switch (state) {
    'missing' => 'Not installed on your Mac',
    'logged_out' => 'Signed out on your Mac',
    'failing' => detail.isEmpty ? 'Stopped working on your Mac' : 'Stopped working: $detail',
    _ => '',
  };
}
