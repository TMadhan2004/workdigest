/// One line of a digest with the evidence behind it.
@immutable
class Statement {
  const Statement({
    required this.text,
    this.evidenceIds = const [],
    this.children = const [],
    this.verified = false,
    this.problems = const [],
  });

  factory Statement.fromJson(Json json) => Statement(
    text: str(json, 'text'),
    evidenceIds: strings(json, 'evidence_ids'),
    children: objects(json, 'children').map(Statement.fromJson).toList(growable: false),
    verified: boolOf(json, 'verified'),
    problems: strings(json, 'problems'),
  );

  final String text;
  final List<String> evidenceIds;
  final List<Statement> children;
  final bool verified;
  final List<String> problems;

  bool get isPlaceholder => text.contains('[missing') || text.contains('[confirm') || text.contains('[ask');

  bool get isUnverified => !verified && problems.isNotEmpty;
}

/// A numbered digest section.
@immutable
class DraftSection {
  const DraftSection({
    required this.key,
    required this.number,
    required this.title,
    this.statements = const [],
    this.inline = false,
    this.titleSuffix = '',
    this.trailer = const [],
    this.source = 'llm',
  });

  factory DraftSection.fromJson(Json json) => DraftSection(
    key: str(json, 'key'),
    number: intOf(json, 'number'),
    title: str(json, 'title'),
    statements: objects(json, 'statements').map(Statement.fromJson).toList(growable: false),
    inline: boolOf(json, 'inline'),
    titleSuffix: str(json, 'title_suffix'),
    trailer: strings(json, 'trailer'),
    source: str(json, 'source', 'llm'),
  );

  final String key;
  final int number;
  final String title;
  final List<Statement> statements;
  final bool inline;
  final String titleSuffix;
  final List<String> trailer;
  final String source;

  /// Sections written by code from facts cannot be regenerated by the LLM.
  bool get regenerable => key != 'prs';

  int get unverifiedCount => _walk(statements).where((s) => s.isUnverified).length;

  int get placeholderCount => statements.isEmpty ? 1 : _walk(statements).where((s) => s.isPlaceholder).length;

  static Iterable<Statement> _walk(List<Statement> items) sync* {
    for (final item in items) {
      yield item;
      yield* _walk(item.children);
    }
  }
}

