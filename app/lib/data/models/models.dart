/// A stored digest version (draft, final or marked sent).
@immutable
class Digest {
  const Digest({
    required this.digestId,
    required this.workDate,
    required this.origin,
    required this.status,
    required this.text,
    required this.header,
    required this.sections,
    required this.closing,
    required this.gaps,
    this.provider,
    this.createdAt,
    this.structureJson = const {},
  });

  factory Digest.fromJson(Json json) {
    final structure = object(json, 'structure');
    return Digest(
      structureJson: structure,
      digestId: str(json, 'digest_id'),
      workDate: str(json, 'work_date'),
      origin: str(json, 'origin'),
      status: str(json, 'status'),
      text: str(json, 'text'),
      header: DraftHeader.fromJson(object(structure, 'header')),
      sections: objects(structure, 'sections').map(DraftSection.fromJson).toList(growable: false),
      closing: objects(structure, 'closing').map(Statement.fromJson).toList(growable: false),
      gaps: objects(json, 'gaps').map(Gap.fromJson).toList(growable: false)
        ..sort((a, b) => a.rank.compareTo(b.rank)),
      provider: strOrNull(json, 'provider'),
      createdAt: dateTimeOrNull(json, 'created_at'),
    );
  }

  final String digestId;
  final String workDate;
  final String origin;
  final String status;
  final String text;
  final DraftHeader header;
  final List<DraftSection> sections;
  final List<Statement> closing;
  final List<Gap> gaps;
  final String? provider;
  final DateTime? createdAt;

  /// The raw structure, kept so an edited version can be saved with the same sections.
  final Json structureJson;

  /// Edited versions point at the generated draft whose evidence they share.
  String get evidenceDigestId => strOrNull(structureJson, 'source_digest_id') ?? digestId;

  bool get isSent => status == 'sent_marked';

  /// Gaps that need a decision (informational "confirm" items excluded).
  int get blockingGaps => gaps.where((g) => g.kind != 'input').length;
}

