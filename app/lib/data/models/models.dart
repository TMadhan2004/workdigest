@immutable
class StandingRule {
  const StandingRule({
    required this.ruleId,
    required this.text,
    required this.checkKind,
    required this.source,
    required this.active,
    this.status = 'active',
    this.params = const {},
  });

  factory StandingRule.fromJson(Json json) => StandingRule(
    ruleId: str(json, 'rule_id'),
    text: str(json, 'text'),
    checkKind: str(json, 'check_kind'),
    source: str(json, 'source'),
    active: boolOf(json, 'active', fallback: true),
    status: strOrNull(json, 'status') ?? 'active',
    params: object(json, 'check_params'),
  );

  final String ruleId;
  final String text;
  final String checkKind;
  final String source;
  final bool active;

  /// For my rules: parsing (the Mac is reading it), needs_review, active or off.
  final String status;

  /// For my rules: what the Mac understood (exclusions and an optional instruction).
  final Json params;

  bool get automatic => checkKind != 'manual';

  /// Typed by the user in the app (as opposed to seed rules and the manager's rules).
  bool get mine => source == 'mine';

  /// The "Understood as" chips, worded like the Mac's `RuleFilters.describe()`.
  List<String> get understood {
    final out = <String>[];
    for (final ref in objects(params, 'exclude_prs')) {
      final repo = strOrNull(ref, 'repo');
      final numbers = (ref['numbers'] as List<dynamic>? ?? const []).map((n) => '#$n').join(', ');
      out.add('Hide ${repo == null ? '' : '$repo '}PRs $numbers');
    }
    final days = intOrNull(params, 'exclude_prs_older_than_days');
    if (days != null) out.add('Hide PRs open more than $days days');
    out
      ..addAll(strings(params, 'exclude_tickets').map((t) => 'Hide ticket $t'))
      ..addAll(strings(params, 'exclude_repos').map((r) => 'Hide repo $r'));
    final instruction = strOrNull(params, 'instruction');
    if (instruction != null && instruction.isNotEmpty) out.add('Instruction for the AI: $instruction');
    return out;
  }

  /// Only an instruction (no exclusion): followed by the AI on a best-effort basis.
  bool get instructionOnly => understood.isNotEmpty && understood.every((u) => u.startsWith('Instruction'));
}

