#!/usr/bin/env python3
"""Embed app/test/fixtures/*.json into a Dart file so tests can load them on a device.

On a phone or emulator the test binary cannot read the host's ``test/fixtures`` folder, and
shipping fixtures as app assets would put them in release builds. ``fixture()`` therefore reads
this generated map. ``test/unit/fixtures_test.dart`` fails when it drifts from the JSON files.

Usage:
    python3 scripts/embed_app_fixtures.py           # rewrite the Dart file
    python3 scripts/embed_app_fixtures.py --check   # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "app" / "test" / "fixtures"
OUTPUT = FIXTURES / "embedded_fixtures.dart"


def render() -> str:
    """The Dart source: one raw string per fixture, keyed by file name."""
    out = [
        "// GENERATED by scripts/embed_app_fixtures.py from test/fixtures/*.json. Do not edit.",
        "// ignore_for_file: type=lint",
        "",
        "const embeddedFixtures = <String, String>{",
    ]
    for path in sorted(FIXTURES.glob("*.json")):
        text = path.read_text(encoding="utf-8")
        if "'''" in text:
            raise SystemExit(f"{path.name} contains ''' and cannot be embedded as a raw string")
        out.append(f"  '{path.name}': r'''{text}''',")
    out.append("};")
    return "\n".join(out) + "\n"


def main() -> int:
    """Entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the Dart file is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("ERROR: embedded_fixtures.dart is stale; run scripts/embed_app_fixtures.py", file=sys.stderr)  # noqa: T201
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")  # noqa: T201
    return 0


if __name__ == "__main__":
    sys.exit(main())
